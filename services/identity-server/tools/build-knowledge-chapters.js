"use strict";

const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const appRoot = path.resolve(__dirname, "..", "public", "app");
const articleRoot = path.resolve(__dirname, "..", "src", "knowledge", "articles");
const outputRoot = path.resolve(__dirname, "..", "src", "knowledge", "generated-chapters");
const sourceFiles = fs.readdirSync(articleRoot)
  .filter((file) => /^knowledge-articles-.*\.js$/.test(file))
  .sort();

function readArticleBundle(file) {
  const source = fs.readFileSync(path.join(articleRoot, file), "utf8");
  const variableName = source.match(/const\s+(KnowledgeArticles\w+)\s*=/)?.[1];
  if (!variableName) throw new Error(`No knowledge article object found in ${file}`);
  const context = {};
  vm.createContext(context);
  vm.runInContext(`${source};this.articles=${variableName};`, context, { filename: file });
  return context.articles;
}

function chapterAssetSource(articleId, article) {
  return `// Generated by tools/build-knowledge-chapters.js. Do not edit directly.\n`+
    `window.KnowledgeArticleRegistry = window.KnowledgeArticleRegistry || {};\n`+
    `window.KnowledgeArticleRegistry[${JSON.stringify(articleId)}]=${JSON.stringify(article)};\n`;
}

fs.mkdirSync(outputRoot, { recursive: true });
const index = {};
const expectedFiles = new Set();

for (const sourceFile of sourceFiles) {
  const articles = readArticleBundle(sourceFile);
  for (const [articleId, article] of Object.entries(articles)) {
    const outputFile = `${articleId}.js`;
    expectedFiles.add(outputFile);
    fs.writeFileSync(path.join(outputRoot, outputFile), chapterAssetSource(articleId, article));
    index[articleId] = {
      endpoint: `/api/platform/knowledge/chapters/${encodeURIComponent(articleId)}`,
      title: article.title,
      summary: article.summary,
      sections: (article.sections || [])
        .filter((section) => section.id)
        .map((section) => ({ id: section.id, heading: section.heading })),
    };
  }
}

for (const file of fs.readdirSync(outputRoot)) {
  if (file.endsWith(".js") && !expectedFiles.has(file)) fs.unlinkSync(path.join(outputRoot, file));
}

const indexSource = `// Generated by tools/build-knowledge-chapters.js. Do not edit directly.\n`+
  `const KnowledgeChapterIndex=${JSON.stringify(index)};\n`;
fs.writeFileSync(path.join(appRoot, "knowledge-chapter-index.js"), indexSource);
console.log(`Knowledge chapters built: ${Object.keys(index).length} chapters from ${sourceFiles.length} source bundles.`);
